-- 量小新 · Supabase + pgvector 初始化
-- 在 Supabase Dashboard -> SQL Editor 里整段执行。
-- 维度 1024 对应 Qwen qwen3.7-text-embedding；换 embedding 模型时改 vector(1024)。

create extension if not exists vector;

-- Supabase 通常把扩展装在 extensions schema；显式加入 search_path，
-- 保证 vector 类型和 vector_cosine_ops 能解析。
set search_path = public, extensions;

create table if not exists public.kb_chunks (
  id            bigint generated by default as identity primary key,
  chunk_id      text not null unique,
  entry_id      text not null,
  doc_type      text not null default 'faq',
  category      text not null,
  title         text not null,
  status        text not null default 'general'
                check (status in ('official', 'general', 'pending')),
  content       text not null,
  search_text   text,
  source        text,
  source_url    text,
  source_page   text,
  updated       text,
  content_hash  text not null,
  embedding     vector(1024),
  metadata      jsonb not null default '{}'::jsonb,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now()
);

comment on table public.kb_chunks is
  '量小新 RAG 知识块；chunk_id = faq:<entry id>，embedding 由 Qwen qwen3.7-text-embedding 生成。';

comment on column public.kb_chunks.embedding is
  '1024 维向量；换 embedding 模型时需改列维度并重建索引。';

-- 分类/内容哈希查询
create index if not exists kb_chunks_category_idx
  on public.kb_chunks (category);

create index if not exists kb_chunks_content_hash_idx
  on public.kb_chunks (content_hash);

-- 向量索引：HNSW + cosine，适合 91 条到几万条
-- 如果 Supabase 的 pgvector 版本不支持 HNSW，删掉这段，先用顺序扫描。
create index if not exists kb_chunks_embedding_hnsw_idx
  on public.kb_chunks
  using hnsw (embedding vector_cosine_ops)
  with (m = 16, ef_construction = 64);

-- 默认不让 anon/authenticated 直接读；后端用 postgres 连接串访问。
-- 如果你以后要通过 Supabase REST/前端直读，再单独加 RLS policy。
alter table public.kb_chunks enable row level security;

-- 可选：手动 update 时自动刷新 updated_at
create or replace function public.touch_kb_chunks_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists kb_chunks_touch_updated_at on public.kb_chunks;

create trigger kb_chunks_touch_updated_at
before update on public.kb_chunks
for each row
execute function public.touch_kb_chunks_updated_at();

-- ------------------------------------------------------------
-- 成本保护：每日 IP 限额 + 问答缓存
-- ------------------------------------------------------------

create table if not exists public.chat_usage (
  ip_hash     text not null,
  day         date not null default current_date,
  count       int not null default 0,
  primary key (ip_hash, day)
);

create index if not exists chat_usage_day_idx
  on public.chat_usage (day);

create table if not exists public.chat_cache (
  cache_key   text primary key,
  payload     jsonb not null,
  expires_at  timestamptz not null,
  created_at  timestamptz not null default now()
);

create index if not exists chat_cache_expires_idx
  on public.chat_cache (expires_at);

alter table public.chat_usage enable row level security;
alter table public.chat_cache enable row level security;
